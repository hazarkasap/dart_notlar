/**
 * Veri Tipleri: Boolean (Mantıksal Veri Tipi)
 * 
 * Sadece iki değer alabilir: true (doğru) veya false (yanlış).
 * Genellikle kontrol yapılarında (if-else) ve döngülerde kullanılır.
 */
void main(List<String> args) {
  bool asalMi = true;
  print(asalMi);
  
  bool calisiyorMu = false;
  print(calisiyorMu);

  // 'var' anahtar kelimesi ile Dart, değişkenin tipini atanan değere göre otomatik belirler.
  // Burada ehliyetVarMi değişkeni boolean olarak tanımlanmış olur.
  var ehliyetVarMi = true;
  print(ehliyetVarMi);
  
}